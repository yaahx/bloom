-- 3. Reviews table
create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  product_id bigint not null references public.products(id) on delete cascade,
  author text not null,
  rating integer not null check (rating >= 1 and rating <= 5),
  comment text not null,
  created_at timestamptz not null default now()
);

create index if not exists reviews_product_id_idx on public.reviews(product_id, created_at desc);

alter table public.reviews enable row level security;

drop policy if exists "Reviews are viewable by everyone" on public.reviews;
create policy "Reviews are viewable by everyone"
  on public.reviews for select
  using (true);

drop policy if exists "Anyone can post a review" on public.reviews;
create policy "Anyone can post a review"
  on public.reviews for insert
  with check (true);

drop policy if exists "Authenticated users can delete reviews" on public.reviews;
create policy "Authenticated users can delete reviews"
  on public.reviews for delete
  using (auth.role() = 'authenticated');

-- Keep products.rating and products.reviews_count in sync automatically
create or replace function public.sync_product_review_stats()
returns trigger
language plpgsql
security definer
as $$
declare
  target_product_id bigint;
  avg_rating numeric(3,1);
  total_count integer;
begin
  target_product_id := coalesce(new.product_id, old.product_id);

  select
    coalesce(round(avg(rating)::numeric, 1), 5.0),
    count(*)::integer
  into avg_rating, total_count
  from public.reviews
  where product_id = target_product_id;

  update public.products
  set
    rating = avg_rating,
    reviews_count = total_count
  where id = target_product_id;

  return coalesce(new, old);
end;
$$;

drop trigger if exists on_review_change on public.reviews;
create trigger on_review_change
  after insert or update or delete on public.reviews
  for each row execute function public.sync_product_review_stats();

-- 4. Orders table
